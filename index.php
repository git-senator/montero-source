<?php
/* ══════════ ЖИВАЯ СТРАНИЦА ══════════

   Щит DDoS-Guard перед сайтом кэширует статические файлы и не слушает
   ни Cache-Control, ни must-revalidate: проверено — изменённый на
   сервере файл он отдавал старым больше трёх минут. Выключается это
   только на его стороне, доступа туда у нас нет.

   Зато динамику он не кэширует вовсе — тоже проверено: три запроса
   подряд к пробному PHP дали три разных ответа. Поэтому страницу
   отдаём через PHP: содержимое лежит в index.html как раньше, а этот
   файл его просто выводит. Для посетителя ничего не меняется, для щита
   страница перестаёт быть кэшируемой, и правка видна сразу.

   DirectoryIndex в .htaccess ставит index.php первым. */
header('Content-Type: text/html; charset=utf-8');
header('Cache-Control: no-cache, no-store, must-revalidate, max-age=0');
header('Pragma: no-cache');
readfile(__DIR__ . '/index.html');
